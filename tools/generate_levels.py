#!/usr/bin/env python3
"""Generate 600 original campaign boards and three deterministic mode variants.

The generated files are STRUCTURAL content only. They are not marked solvable until a
trajectory-aware gameplay solver has tested the exact physics and queue.
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "godot_project" / "levels"
TARGET_LEVELS = 600
COLS = 11
MAX_ROWS = 20
COLORS = ["red", "blue", "green", "yellow", "purple", "orange"]
ROW_PATTERNS = [(0, 4, 8), (1, 4, 8), (0, 3, 7), (1, 5, 8), (0, 4, 7), (1, 4, 7)]
MODES = ("classic", "hard", "challenge")


class LCG:
    """Small fixed generator so a level can be regenerated byte-for-byte."""
    def __init__(self, seed: int):
        self.state = seed & 0xFFFFFFFF

    def next_u32(self) -> int:
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state

    def randbelow(self, upper: int) -> int:
        if upper <= 0:
            raise ValueError("upper must be positive")
        return self.next_u32() % upper

    def shuffle(self, values: list[Any]) -> list[Any]:
        result = list(values)
        for index in range(len(result) - 1, 0, -1):
            other = self.randbelow(index + 1)
            result[index], result[other] = result[other], result[index]
        return result

    def sample(self, values: list[Any], count: int) -> list[Any]:
        return self.shuffle(values)[:count]


def _level_seed(level_id: int, salt: int = 0) -> int:
    return (20261109 + level_id * 7919 + salt * 104729) & 0x7FFFFFFF


def build_classic_level(level_id: int) -> dict[str, Any]:
    if not 1 <= level_id <= TARGET_LEVELS:
        raise ValueError(f"level_id must be within 1..{TARGET_LEVELS}")
    seed = _level_seed(level_id)
    rng = LCG(seed)
    color_count = min(6, 3 + (level_id - 1) // 100)
    palette = COLORS[:color_count]
    row_count = min(14, 4 + (level_id - 1) // 48)
    layout: list[str] = []

    for row_no in range(row_count):
        cells = ["."] * COLS
        starts = sorted(rng.shuffle(list(ROW_PATTERNS[(row_no + level_id) % len(ROW_PATTERNS)])))
        group_colors = rng.sample(palette, 3)
        for start, color in zip(starts, group_colors):
            token = str(palette.index(color) + 1)
            for offset in range(3):
                cells[start + offset] = token
        layout.append("".join(cells))

    bubble_count = sum(char.isdigit() for line in layout for char in line)
    score_target = max(100, bubble_count * 8)
    shots = min(60, max(12, row_count * 3 + 5))
    stars = {
        "1": max(50, int(score_target * 0.45)),
        "2": max(100, int(score_target * 0.68)),
        "3": max(150, int(score_target * 0.90)),
    }
    return {
        "id": level_id,
        "world": 1 + (level_id - 1) // 100,
        "name": f"Bubble Bay {level_id:03d}",
        "mode": "classic",
        "grid": {"cols": COLS, "rows": MAX_ROWS, "seed": seed},
        "shots": shots,
        "palette": palette,
        "layout": layout,
        "blockers": [],
        "objectives": [{"type": "clear_all"}],
        "stars": stars,
        "rewards": {"coins": 40, "firstClearBonus": 100},
        "content_status": "generated_structural_only",
        "playability_status": "requires_trajectory_solver",
        "notes": "Original deterministic campaign content; structural validation only.",
    }


def _empty_cells(level: dict[str, Any]) -> list[tuple[int, int]]:
    layout = level["layout"]
    used = {(int(item["row"]), int(item["col"])) for item in level["blockers"]}
    return [
        (row, col)
        for row, line in enumerate(layout)
        for col, token in enumerate(line)
        if token == "." and (row, col) not in used
    ]


def build_hard_variant(base: dict[str, Any], level_id: int) -> dict[str, Any]:
    data = json.loads(json.dumps(base))
    data["mode"] = "hard"
    data["name"] = f"Hard Tide {level_id:03d}"
    data["grid"]["seed"] = _level_seed(level_id, 1)
    data["shots"] = max(8, int(base["shots"] * 0.78))
    rng = LCG(_level_seed(level_id, 11))
    candidates = _empty_cells(data)
    obstacle_count = 0 if level_id < 15 else (1 + int(level_id >= 180) + int(level_id >= 360))
    selected = rng.sample(candidates, min(obstacle_count, len(candidates)))
    blockers = []
    for index, (row, col) in enumerate(selected):
        blockers.append({
            "row": row,
            "col": col,
            "type": "ice" if index % 2 == 0 else "chain",
            "hp": 1 if level_id < 240 else 2,
        })
    data["blockers"] = blockers
    data["rewards"] = {"coins": 55, "firstClearBonus": 125}
    data["notes"] = "Hard mode uses a lower move budget and original blocker variants; solver validation pending."
    return data


def build_challenge_variant(base: dict[str, Any], level_id: int) -> dict[str, Any]:
    data = json.loads(json.dumps(base))
    data["mode"] = "challenge"
    data["name"] = f"Challenge Current {level_id:03d}"
    data["grid"]["seed"] = _level_seed(level_id, 2)
    data["shots"] = max(9, int(base["shots"] * 0.90))
    counts = Counter(char for line in data["layout"] for char in line if char.isdigit())
    if not counts:
        raise ValueError(f"level {level_id} has no coloured bubbles")
    target_token = min(counts, key=lambda token: (-counts[token], token))
    target_color = data["palette"][int(target_token) - 1]
    objective_cycle = (level_id - 1) % 4
    bubble_count = sum(counts.values())
    if objective_cycle == 0:
        objective = {"type": "clear_color", "color": target_color}
    elif objective_cycle == 1:
        objective = {"type": "pop_count", "count": max(6, int(bubble_count * 0.30))}
    elif objective_cycle == 2:
        objective = {"type": "score", "target": max(100, int(bubble_count * 12))}
    else:
        objective = {"type": "clear_all"}
    data["objectives"] = [objective]
    data["rewards"] = {"coins": 50, "firstClearBonus": 125}
    data["notes"] = "Challenge mode uses a focused objective variant; trajectory solver validation pending."
    return data


def _validate_unique_layouts(levels: list[dict[str, Any]], mode: str) -> None:
    signatures: set[tuple[str, ...]] = set()
    for level in levels:
        signature = tuple(level["layout"])
        if signature in signatures:
            raise SystemExit(f"Duplicate {mode} layout signature at level {level['id']}")
        signatures.add(signature)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    modes: dict[str, list[dict[str, Any]]] = {mode: [] for mode in MODES}
    index: list[dict[str, Any]] = []

    for level_id in range(1, TARGET_LEVELS + 1):
        classic = build_classic_level(level_id)
        modes["classic"].append(classic)
        modes["hard"].append(build_hard_variant(classic, level_id))
        modes["challenge"].append(build_challenge_variant(classic, level_id))
        (OUT / f"level_{level_id:03d}.json").write_text(
            json.dumps(classic, indent=2) + "\n", encoding="utf-8"
        )
        index.append({
            "id": level_id,
            "world": classic["world"],
            "file": f"level_{level_id:03d}.json",
            "name": classic["name"],
            "modes": list(MODES),
            "status": "requires_trajectory_solver",
        })

    for mode in MODES:
        _validate_unique_layouts(modes[mode], mode)

    (OUT / "index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    pack = {
        "schema_version": 2,
        "campaign_levels": TARGET_LEVELS,
        "mode_count": len(MODES),
        "logical_variants": TARGET_LEVELS * len(MODES),
        "generator_version": "campaign600-three-modes-lcg-v2",
        "modes": modes,
        "levels": modes["classic"],
    }
    (OUT / "campaign_600.json").write_text(
        json.dumps(pack, separators=(",", ":")) + "\n", encoding="utf-8"
    )
    print("Generated 600 unique base boards and 1,800 mode variants.")
    print("Modes: classic=600, hard=600, challenge=600.")
    print("Status: structural only; trajectory-aware solvability is NOT asserted.")


if __name__ == "__main__":
    main()
