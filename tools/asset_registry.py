#!/usr/bin/env python3
"""
Generate godot_project/scripts/AssetRegistry.gd from whatever is actually in
godot_project/assets/. Nothing is hard-coded: drop a new sprite in and re-run.

    python3 tools/asset_registry.py

The registry is a catalogue, not a loader. Its job is to make a missing or
misspelled asset a build failure instead of a silent fallback to a drawn circle.
"""
from __future__ import annotations

import sys
from pathlib import Path

ASSETS = Path("godot_project/assets")
OUT = Path("godot_project/scripts/AssetRegistry.gd")
TEXTURE_EXT = {".png", ".jpg", ".jpeg", ".webp"}
AUDIO_EXT = {".wav", ".ogg", ".mp3"}


def key_for(rel: Path) -> str:
    stem = rel.with_suffix("").as_posix().replace("/", "_")
    return stem


def main() -> int:
    if not ASSETS.is_dir():
        print(f"no assets directory at {ASSETS}")
        return 1

    textures: dict[str, str] = {}
    audio: dict[str, str] = {}
    for path in sorted(ASSETS.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ASSETS)
        if path.suffix.lower() in TEXTURE_EXT:
            textures[key_for(rel)] = "res://assets/" + rel.as_posix()
        elif path.suffix.lower() in AUDIO_EXT:
            audio[key_for(rel)] = "res://assets/" + rel.as_posix()

    lines = [
        "class_name AssetRegistry",
        "extends RefCounted",
        "## Generated by tools/asset_registry.py - do not edit by hand.",
        "##",
        f"## {len(textures)} textures, {len(audio)} audio files, all taken from",
        "## godot_project/assets/. Regenerate after adding or renaming an asset.",
        "",
        "const TEXTURES := {",
    ]
    for k, v in textures.items():
        lines.append(f'\t"{k}": "{v}",')
    lines.append("}")
    lines.append("")
    lines.append("const AUDIO := {")
    for k, v in audio.items():
        lines.append(f'\t"{k}": "{v}",')
    lines.append("}")
    lines.append("")
    lines.append('''
static func texture_path(key: String) -> String:
	if not TEXTURES.has(key):
		push_error("AssetRegistry: no texture named %s" % key)
		return ""
	return TEXTURES[key]


static func audio_path(key: String) -> String:
	if not AUDIO.has(key):
		push_error("AssetRegistry: no audio named %s" % key)
		return ""
	return AUDIO[key]


static func texture(key: String) -> Texture2D:
	var path := texture_path(key)
	if path == "" or not ResourceLoader.exists(path):
		return null
	return load(path) as Texture2D


static func all_paths() -> PackedStringArray:
	var out := PackedStringArray()
	for v in TEXTURES.values():
		out.append(str(v))
	for v in AUDIO.values():
		out.append(str(v))
	return out
''')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}: {len(textures)} textures, {len(audio)} audio")
    return 0


if __name__ == "__main__":
    sys.exit(main())
